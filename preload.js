const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('api', {
  aoReceberDados: (fn) => ipcRenderer.on('dados', (_e, d) => fn(d)),
  aoMaximizar: (fn) => ipcRenderer.on('maximizada', (_e, m) => fn(m)),
  jogos: () => ipcRenderer.invoke('jogos'),
  layout: (mapa) => ipcRenderer.send('layout', mapa),
  janela: (acao) => ipcRenderer.send('janela', acao),
  nova: (jogo) => ipcRenderer.send('nova', jogo),
  remover: (conta) => ipcRenderer.send('remover', conta),
  entrar: (conta) => ipcRenderer.send('entrar', conta),
  atualizar: () => ipcRenderer.send('atualizar'),
  ferramenta: (jogo, conta, escolha) => ipcRenderer.invoke('ferramenta', jogo, conta, escolha),
  acao: (conta, acao) => ipcRenderer.invoke('acao', conta, acao),
  recarregarContas: () => ipcRenderer.invoke('recarregar-contas'),
  vendaPreparar: (conta) => ipcRenderer.invoke('venda-preparar', conta),
  depotListar: (conta) => ipcRenderer.invoke('depot-listar', conta),
  depotGuardar: (conta, chave) => ipcRenderer.invoke('depot-guardar', conta, chave),
  vendaConcluir: (conta, vender) => ipcRenderer.invoke('venda-concluir', conta, vender),
  aoAtualizacao: (fn) => {
    ipcRenderer.on('atualizacao', (_e, v) => fn(v));
    ipcRenderer.invoke('versao-baixada').then((v) => v && fn(v)); // já baixada antes do painel abrir
  },
  instalarAtualizacao: () => ipcRenderer.send('instalar-atualizacao'),
  aoLives: (fn) => ipcRenderer.on('lives', (_e, l) => fn(l)),
  aoVoltar: (fn) => ipcRenderer.on('voltar', () => fn()),
  livesLigar: (ligar) => ipcRenderer.send('lives-ligar', ligar),
  livesPedir: () => ipcRenderer.send('lives-pedir'),
  livesEntrar: () => ipcRenderer.send('lives-entrar'),
  livesMax: (n) => ipcRenderer.send('lives-max', n),
  livesSoChat: (soChat) => ipcRenderer.send('lives-so-chat', soChat),
  aoSniper: (fn) => ipcRenderer.on('sniper', (_e, s) => fn(s)),
  sniperPedir: () => ipcRenderer.send('sniper-pedir'),
  sniperSalvar: (novo) => ipcRenderer.send('sniper-salvar', novo),
  sniperCatalogo: () => ipcRenderer.invoke('sniper-catalogo'),
  sniperPrecos: () => ipcRenderer.invoke('sniper-precos'),
  sniperHistorico: () => ipcRenderer.send('sniper-historico'),
  sniperLimpar: () => ipcRenderer.send('sniper-limpar'),
  sniperZerarDia: () => ipcRenderer.send('sniper-zerar-dia'),
  sniperRegistro: (filtro) => ipcRenderer.invoke('sniper-registro', filtro),
  aoSniperComprado: (fn) => ipcRenderer.on('sniper-comprado', (_e, linha) => fn(linha)),
  sniperCompras: () => ipcRenderer.invoke('sniper-compras'),
  sniperComprasVisto: () => ipcRenderer.send('sniper-compras-visto'),
});
